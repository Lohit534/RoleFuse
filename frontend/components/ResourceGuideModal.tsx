interface ResourceGuideModalProps {
  guideKey: string | null;
  onClose: () => void;
  isAuthenticated?: boolean;
}

export default function ResourceGuideModal({
  guideKey,
  onClose,
  isAuthenticated = false,
}: ResourceGuideModalProps) {
  const router = useRouter();
  if (!guideKey || !GUIDE_REGISTRY[guideKey]) return null;

  const guide = GUIDE_REGISTRY[guideKey];

  const handleAction = () => {
    onClose();
    if (guide.ctaLink.startsWith("/dashboard") && !isAuthenticated) {
      router.push(`/auth/login?redirect=${encodeURIComponent(guide.ctaLink)}`);
    } else {
      router.push(guide.ctaLink);
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-3 sm:p-6 bg-slate-900/60 backdrop-blur-sm animate-in fade-in duration-200">
      <div
        className="relative w-full max-w-2xl bg-white rounded-3xl shadow-2xl border border-slate-200 overflow-hidden flex flex-col max-h-[90vh] animate-in zoom-in-95 duration-200"
        onClick={(e) => e.stopPropagation()}
      >
        {/* Header */}
        <div className="px-6 py-5 border-b border-slate-100 flex items-center justify-between bg-slate-50/70">
          <div className="flex items-center gap-3">
            <div className="h-10 w-10 rounded-2xl bg-teal-50 border border-teal-200 flex items-center justify-center text-[#087F6E]">
              <BookOpen className="h-5 w-5" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <span className="px-2 py-0.5 rounded-full text-[10px] font-black uppercase tracking-wider bg-teal-50 text-[#087F6E] border border-teal-200">
                  {guide.category}
                </span>
                <span className="text-xs text-slate-400 font-medium">&bull; {guide.readTime}</span>
              </div>
              <h3 className="font-heading font-extrabold text-lg text-slate-900 mt-0.5">
                {guide.title}
              </h3>
            </div>
          </div>
          <button
            onClick={onClose}
            aria-label="Close guide"
            className="p-2 rounded-xl text-slate-400 hover:text-slate-700 hover:bg-slate-100 transition-colors cursor-pointer"
          >
            <X className="h-5 w-5" />
          </button>
        </div>

        {/* Body Content */}
        <div className="p-6 overflow-y-auto space-y-5 text-slate-700 text-sm">
          {/* Overview */}
          <p className="leading-relaxed text-slate-600 bg-slate-50/80 p-4 rounded-2xl border border-slate-200/80">
            {guide.overview}
          </p>

          {/* Key Insights */}
          <div className="space-y-3">
            <h4 className="text-xs font-bold uppercase tracking-wider text-slate-400">
              Key ATS Insights
            </h4>
            <div className="space-y-2.5">
              {guide.keyPoints.map((pt, i) => (
                <div key={i} className="p-3.5 rounded-xl border border-slate-200/90 bg-white space-y-1 shadow-2xs">
                  <div className="flex items-center gap-2 font-bold text-slate-900 text-xs">
                    <CheckCircle2 className="h-4 w-4 text-[#087F6E] shrink-0" />
                    <span>{pt.title}</span>
                  </div>
                  <p className="text-xs text-slate-600 pl-6 leading-relaxed">{pt.desc}</p>
                </div>
              ))}
            </div>
          </div>

          {/* Pro Tip */}
          <div className="p-4 rounded-2xl bg-amber-50/60 border border-amber-200/80 flex items-start gap-3">
            <Lightbulb className="h-5 w-5 text-amber-600 shrink-0 mt-0.5" />
            <div className="space-y-0.5">
              <h5 className="font-bold text-xs text-amber-900">FastHire Recommendation</h5>
              <p className="text-xs text-amber-800 leading-relaxed">{guide.proTip}</p>
            </div>
          </div>
        </div>

        {/* Footer Actions */}
        <div className="px-6 py-4 border-t border-slate-100 bg-slate-50/70 flex items-center justify-between gap-3">
          <Button
            variant="outline"
            onClick={onClose}
            className="h-10 px-4 text-xs font-semibold rounded-xl text-slate-600 hover:bg-slate-100"
          >
            Close Guide
          </Button>
          <Button
            onClick={handleAction}
            className="h-10 px-5 bg-[#087F6E] hover:bg-[#075E53] text-white text-xs font-bold rounded-xl shadow-xs gap-2 cursor-pointer"
          >
            <span>{guide.ctaText}</span>
            <ArrowRight className="h-3.5 w-3.5" />
          </Button>
        </div>
      </div>
    </div>
  );
}
